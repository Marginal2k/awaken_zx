#!/usr/bin/env python3
"""assets/gfx/*.png  ->  build/gen/{stscr.C, stscr.len, SECTAB.inc, PANEL.C, intro_logo.scr, PRO.f, FONT.f, KSPOplus.s}
Packed pictures: if the PNG is pixel-identical to the one extracted from the original game (assets/gfx/cache.json) the original packed bytes
(assets/gfx/orig/) are used (byte-identical build); otherwise the picture is converted (8x8 attribute rule) and packed by tools/assets/hrust.py,
the result is cached in build/gfxcache/ (so only changed pictures are packed again)."""
import os, sys, json, hashlib
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import zxgfx, hrust
from PIL import Image

SECTAB_ORIG = [13, 11, 11, 12, 8, 14, 19, 15, 15, 13, 19, 12, 16, 20, 21, 20]
MAX_SECTORS = max(SECTAB_ORIG)      # the loader buffer was sized for the biggest original picture (21 sectors)


def packed_picture(root, gfx, cache, name, im, layout='screen'):
    h = zxgfx.pixels_hash(im)
    c = cache.get(name)
    if c and c['pixels'] == h:
        return open(os.path.join(gfx, c['orig']), 'rb').read(), True
    cdir = os.path.join(root, 'build', 'gfxcache')
    os.makedirs(cdir, exist_ok=True)
    cf = os.path.join(cdir, h + '.' + layout + '.hr')
    if os.path.exists(cf):
        return open(cf, 'rb').read(), False
    print('gen_gfx: packing %s (changed picture)' % name)
    scr = zxgfx.image_to_scr(im, name, layout)
    pk = hrust.pack(scr)
    open(cf, 'wb').write(pk)
    return pk, False


def generate(root, outdir):
    gfx = os.path.join(root, 'assets', 'gfx')
    cache = json.load(open(os.path.join(gfx, 'cache.json')))
    os.makedirs(outdir, exist_ok=True)
    # --- station backgrounds
    chunks = []
    tab = []
    first_len = None
    for i in range(16):
        name = 'station_bg_%02d.png' % (i + 1)
        pk, orig = packed_picture(root, gfx, cache, name, Image.open(os.path.join(gfx, name)), 'cell')
        if orig:
            ch = pk                              # full sectors as on the original disk
        else:
            ch = pk + bytes((-len(pk)) % 256)
        n = len(ch) // 256
        if n > MAX_SECTORS:
            raise SystemExit('%s packs to %d sectors; the station loader buffer allows %d.  Simplify the picture (fewer dither details).' % (name, n, MAX_SECTORS))
        if i == 0:
            first_len = pk[4] | pk[5] << 8
        chunks.append(ch)
        tab.append(n)
    open(os.path.join(outdir, 'stscr.C'), 'wb').write(b''.join(chunks))
    open(os.path.join(outdir, 'stscr.len'), 'w').write('%d %d\n' % (first_len, sum(tab)))
    open(os.path.join(outdir, 'SECTAB.inc'), 'w', newline='\n').write(
        '; GENERATED by tools/assets/gen_gfx.py - sector counts of the 16 packed pictures in stscr.C\n            db   ' + ','.join(map(str, tab)) + '\n')
    # --- panel
    pk, orig = packed_picture(root, gfx, cache, 'panel.png', Image.open(os.path.join(gfx, 'panel.png')))
    open(os.path.join(outdir, 'PANEL.C'), 'wb').write(pk)
    # --- raw screen (intro logo)
    im = Image.open(os.path.join(gfx, 'intro_logo.png'))
    c = cache['intro_logo.png']
    if c['pixels'] == zxgfx.pixels_hash(im):
        data = open(os.path.join(gfx, c['orig']), 'rb').read()
    else:
        data = zxgfx.image_to_scr(im, 'intro_logo.png')
    open(os.path.join(outdir, 'intro_logo.scr'), 'wb').write(data)
    # --- intro closing picture: depacker + packed picture blob (original blob if the picture is unchanged, else our RLE packer)
    im = Image.open(os.path.join(gfx, 'intro_closing.png'))
    c = cache['intro_closing.png']
    if c['pixels'] == zxgfx.pixels_hash(im):
        blob = open(os.path.join(gfx, c['orig']), 'rb').read()
    else:
        import rlepack
        blob = rlepack.pack(zxgfx.image_to_scr(im, 'intro_closing.png'))
        if len(blob) > 0x1B00:
            raise SystemExit('intro_closing.png packs to %d bytes; the intro copies at most 6912 bytes of the blob.  Simplify the picture (long runs of equal bytes pack well).' % len(blob))
    open(os.path.join(outdir, 'intro_depack.bin'), 'wb').write(blob)
    # --- the ending FINALF.C: code (assets/ending/finalf_code.bin) + three 1-bit screens (the code copies them from #62A9 into banks 7, 0, 1)
    code = open(os.path.join(root, 'assets', 'ending', 'finalf_code.bin'), 'rb').read()
    bms = []
    for n in ('ending_1_spas_mir', 'ending_2_sdelal_eto', 'ending_3_galaxy'):
        bms.append(zxgfx.image_to_bitmap(Image.open(os.path.join(gfx, n + '.png')), n))
    open(os.path.join(outdir, 'FINALF.C'), 'wb').write(code[:0x2A9] + b''.join(bms) + code[0x2A9:])
    # --- fonts and cursors (exact conversions)
    widths = []
    for l in open(os.path.join(gfx, 'pro_font_widths.csv'), encoding='utf-8'):
        if l.startswith('#') or not l.strip():
            continue
        parts = l.rstrip('\n').rsplit(',', 1)
        widths.append(int(parts[1]))
    if len(widths) != 256:
        raise SystemExit('pro_font_widths.csv: 256 rows expected')
    open(os.path.join(outdir, 'PRO.f'), 'wb').write(zxgfx.png_to_pro(Image.open(os.path.join(gfx, 'pro_font.png')), widths))
    open(os.path.join(outdir, 'FONT.f'), 'wb').write(zxgfx.png_to_font(Image.open(os.path.join(gfx, 'panel_font.png')), 208))
    open(os.path.join(outdir, 'KSPOplus.s'), 'wb').write(zxgfx.png_to_cursors(Image.open(os.path.join(gfx, 'cursors.png')), 12))
    return 8


if __name__ == '__main__':
    root = os.path.join(HERE, '..', '..')
    print('gen_gfx: %d outputs' % generate(root, os.path.join(root, 'build', 'gen')))
