#!/usr/bin/env python3
"""Extract all files of all TRD/SCL images (archive + reference) -> work/extract/<disk>/ + catalogue."""
import os, sys, struct, json, hashlib, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_image(path):
    d = open(path, 'rb').read()
    if d[:8] == b'SINCLAIR':
        n = d[8]
        ents = []
        p = 9
        for i in range(n):
            ents.append(d[p:p+14]); p += 14
        img = bytearray(655360)
        sec = 16
        cat = bytearray()
        for e in ents:
            nm, ty, st, ln, sc = e[:8], e[8], e[9]|e[10]<<8, e[11]|e[12]<<8, e[13]
            cat += nm + bytes([ty]) + struct.pack('<HH', st, ln) + bytes([sc, sec % 16, sec // 16])
            img[sec*256:sec*256+sc*256] = d[p:p+sc*256]
            p += sc*256; sec += sc
        img[0:len(cat)] = cat
        return bytes(img), 'SCL'
    return d, 'TRD'

def catalogue(img):
    out = []
    for i in range(128):
        e = img[i*16:i*16+16]
        if e[0] == 0: break
        deleted = e[0] == 1
        name = e[:8].decode('latin1')
        ty = chr(e[8]); st, ln = struct.unpack('<HH', e[9:13])
        secs, s0, t0 = e[13], e[14], e[15]
        off = (t0*16+s0)*256
        out.append(dict(idx=i, deleted=deleted, name=name, type=ty, start=st, length=ln, sectors=secs,
                        sec=s0, trk=t0, off=off))
    return out

def safe(s):
    return ''.join(c if (c.isalnum() or c in '._-') else '_%02x' % ord(c) for c in s.rstrip())

def main():
    disks = {}
    for p in sorted(glob.glob(ROOT + '/archive/*.trd')):
        disks[os.path.basename(p)[:-4]] = p
    refmap = {'AwakenV0.2Demo.trd/Awakenv02.trd': 'v02', 'AwakenV0.1Demo.trd/AWAKEN_D.TRD': 'v01',
              'AWAKEN_D/AWAKEN_D.SCL': 'awaken_d', 'AWAK_SDC/AWAK_SDC.SCL': 'awak_sdc',
              'SPACE/SPACE.SCL': 'space', 'SWH_000/SWH_000.SCL': 'swh_000'}
    for k, v in refmap.items():       # the released demos (zxart.ee) are optional: not in the repository
        if os.path.exists(ROOT + '/reference/' + k):
            disks[v] = ROOT + '/reference/' + k
        else:
            print('note: reference/%s not present (demo releases are optional, see README)' % k)
    allcat = {}
    for dn, p in disks.items():
        img, kind = load_image(p)
        cat = catalogue(img)
        od = '%s/work/extract/%s' % (ROOT, dn)
        os.makedirs(od, exist_ok=True)
        seen = {}
        for c in cat:
            data = img[c['off']:c['off']+c['sectors']*256]
            # logical length: for type B/C/etc the "length" field is the real length except for 'a'?? keep full sectors
            fn = '%s.%s' % (safe(c['name']), c['type'])
            if c['deleted']: fn = 'DEL_' + fn
            if fn.lower() in seen:
                seen[fn.lower()] += 1; fn = fn.rsplit('.', 1)[0] + '~%d.%s' % (seen[fn.lower()], c['type'])
            else: seen[fn.lower()] = 0
            # trim to logical length when it fits within sectors
            ln = c['length']
            # logical file = first `length` bytes (BASIC keeps whole sectors: length excludes the 4 autostart bytes)
            trimmed = data[:ln] if (0 < ln <= len(data) and c['type'] != 'B') else data
            open(od + '/' + fn, 'wb').write(trimmed)
            c['full_md5'] = hashlib.md5(data).hexdigest()
            c['file'] = fn; c['md5'] = hashlib.md5(trimmed).hexdigest(); c['size'] = len(trimmed)
        allcat[dn] = dict(path=os.path.relpath(p, ROOT), kind=kind, files=cat)
    json.dump(allcat, open(ROOT + '/work/catalogue.json', 'w'), indent=1)
    # md catalogue
    md = ['# Catalogue (generated by tools/extract.py)\n']
    byhash = {}
    for dn, d in allcat.items():
        md.append('\n## %s (%s, %s)\n\n| # | name | t | start | len | secs | md5 |\n|--|--|--|--|--|--|--|' % (dn, d['path'], d['kind']))
        for c in d['files']:
            md.append('| %d | %s%s | %s | %d | %d | %d | %s |' % (c['idx'], '(del) ' if c['deleted'] else '', c['name'].rstrip(), c['type'], c['start'], c['length'], c['sectors'], c['md5'][:8]))
            byhash.setdefault(c['md5'], []).append('%s/%s' % (dn, c['file']))
    md.append('\n## Duplicates (identical sector data)\n')
    for h, l in byhash.items():
        if len(l) > 1: md.append('- `%s`: %s' % (h[:8], ', '.join(l)))
    open(ROOT + '/work/catalogue.md', 'w', encoding='utf-8').write('\n'.join(md))
    print('disks', len(allcat), 'files', sum(len(d['files']) for d in allcat.values()))
main()
