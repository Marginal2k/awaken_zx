#!/usr/bin/env python3
"""assets/text/*.txt, rules.paradox  ->  build/gen/<LABEL>.inc (db lines), build/gen/*.tok, build/gen/C_SCENAR.t
Run by build.py before the assembly.  Every [LABEL] section of every .txt file becomes build/gen/LABEL.inc (or LABEL itself
when the label contains a dot: ship.tok, help.tok, skim.tok = raw binary files that the sources `incbin`)."""
import os, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from textlib import parse_file, section_bytes, emit_db, t2b

HEADER = '; GENERATED by tools/assets/gen_text.py from assets/text/%s - DO NOT EDIT (edit the text file, the build regenerates this)\n'


def generate(root, outdir):
    os.makedirs(outdir, exist_ok=True)
    seen = {}
    n = 0
    for path in sorted(glob.glob(os.path.join(root, 'assets', 'text', '*.txt'))):
        base = os.path.basename(path)
        for label, opts, items in parse_file(path):
            if label in seen:
                raise SystemExit('%s: section [%s] also defined in %s' % (base, label, seen[label]))
            seen[label] = base
            end = int(opts.get('end', '0A'), 16)
            bs = section_bytes(items, end)
            if '.' in label:
                open(os.path.join(outdir, label), 'wb').write(bs)
            else:
                open(os.path.join(outdir, label + '.inc'), 'w', newline='\n').write(HEADER % base + emit_db(bs))
            n += 1
    # trade-rules script: one statement group per line in the file = CR in the game; encoded as CP866 (comments)
    p = os.path.join(root, 'assets', 'text', 'rules.paradox')
    if os.path.exists(p):
        txt = open(p, encoding='utf-8', newline='').read().replace('\r\n', '\n').replace('\n', '\r')
        try:
            data = txt.encode('cp866')
        except UnicodeEncodeError as e:
            raise SystemExit('rules.paradox: character %r is not in CP866' % txt[e.start])
        open(os.path.join(outdir, 'C_SCENAR.t'), 'wb').write(data)
    return n


if __name__ == '__main__':
    root = os.path.join(HERE, '..', '..')
    print('gen_text: %d sections' % generate(root, os.path.join(root, 'build', 'gen')))
