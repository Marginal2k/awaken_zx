;==============================================================================
; CNVVOXS3 - одноразовый конвертер: воксельный спрайт #0X -> #XX
;
; ORG #6000. Вход: drv2.bin по #C000, вырезает спрайт 14x32.
;
; Часть набора STORM (прототип Awaken 1997/98), не входит в основную игру. Подробности: docs/STORM.md,
; таблица переименований меток: docs/STORM_LABELS.md. Собирается sjasmplus (см. make_*.asm).
;==============================================================================

        ; Перекодирует спрайт воксельный из
        ; Формата #0х в #хх
        ; Плюс вырезает спрайт размером
        org  #6000
        ld   de,#8000
        ld   hl,#C000
        ld   b,32
M2
        push bc
        push hl
        ld   b,14
M1
        ld   a,(hl)
        ld   c,a
        dup  4
        rlca
        edup
        or   c
        ld   (de),a
        inc  hl
        inc  de
        djnz M1
        pop  hl
        ld   bc,64
        add  hl,bc
        pop  bc
        djnz M2
        ret
        org  #C000
        incbin "assets/drv2.bin"
