#!/usr/bin/env python3
"""Group same-named modules across the developer disks and measure how different they are -> docs/VERSIONS.md"""
import os, re, json, hashlib, difflib, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
idx = json.load(open(ROOT + '/work/source_index.json', encoding='utf8'))


def norm(path):
    t = open(ROOT + '/' + path, encoding='utf8').read().split('\n')
    return [re.sub(r'\s+', '', l).upper() for l in t if l.strip()]


groups = collections.defaultdict(list)
for e in idx:
    key = re.sub(r'[_~].*$', '', e['name']).upper().replace('_', '')
    key = re.sub(r'\+$', '', key)
    groups[key].append(e)

out = ['# Module versions across the developer disks (generated by tools/compare_versions.py)', '',
       'Similarity = difflib ratio of the normalised (whitespace-collapsed, blank lines removed) decoded text.',
       'Formats: zasm = ZASM 3.10 tokenized, storm = STORM tokenized (awk2), text = plain text (awk4 `C` files with start==len).', '']
for k in sorted(groups):
    g = groups[k]
    if len(g) < 2: continue
    out.append('## %s' % k)
    out.append('')
    out.append('| copy | format | lines | md5(text) |')
    out.append('|--|--|--|--|')
    texts = []
    for e in g:
        n = norm(e['out'])
        texts.append(n)
        out.append('| %s/%s | %s | %d | %s |' % (e['disk'], e['name'], e['fmt'], len(n), hashlib.md5('\n'.join(n).encode()).hexdigest()[:8]))
    out.append('')
    out.append('Pairwise similarity:')
    out.append('')
    for i in range(len(g)):
        for j in range(i + 1, len(g)):
            if texts[i] == texts[j]:
                r = 1.0
            else:
                r = difflib.SequenceMatcher(None, texts[i], texts[j], autojunk=False).quick_ratio() if len(texts[i]) * len(texts[j]) > 4e6 \
                    else difflib.SequenceMatcher(None, texts[i], texts[j], autojunk=False).ratio()
            out.append('- %s/%s  vs  %s/%s : %.3f%s' % (g[i]['disk'], g[i]['name'], g[j]['disk'], g[j]['name'], r, '  (identical)' if r == 1.0 else ''))
    out.append('')
open(ROOT + '/docs/VERSIONS.md', 'w', encoding='utf8').write('\n'.join(out))
print('groups with >1 copy:', sum(1 for g in groups.values() if len(g) > 1))
