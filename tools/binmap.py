#!/usr/bin/env python3
"""Cross-reference every non-source file of every disk/image by content (md5 of the logical file) -> docs/BINARIES.md"""
import os, json, collections
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
cat = json.load(open(ROOT + '/work/catalogue.json'))
DEV = ['awk1', 'awk2', 'awk3', 'awk4', 'awk5', 'awk6']
REF = ['v02', 'v01', 'awaken_d', 'awak_sdc', 'space', 'swh_000']
by = collections.defaultdict(list)
for dn in DEV + REF:
    for c in cat[dn]['files']:
        by[c['md5']].append((dn, c))
out = ['# Binary / data files and where their copies are (generated by tools/binmap.py)', '',
       'Content identity = md5 of the logical file (first `length` bytes). `ref` = released demo disks, `dev` = developer disks awk1..6.', '']
out.append('## Reference demo v0.2 (Awakenv02.trd) - every file and its provenance\n')
out.append('| file | type | start | len | identical copies on dev disks | same name on dev disks (different content) |')
out.append('|--|--|--|--|--|--|')
names = collections.defaultdict(list)
for dn in DEV:
    for c in cat[dn]['files']:
        names[c['name'].strip().lower()].append((dn, c))
for c in cat['v02']['files']:
    same = [d for d, x in by[c['md5']] if d in DEV]
    nm = [d + ('(%d)' % x['size']) for d, x in names.get(c['name'].strip().lower(), []) if d in DEV and x['md5'] != c['md5']]
    out.append('| %s | %s | %d | %d | %s | %s |' % (c['name'].strip().replace('|', '/'), c['type'], c['start'], c['length'], ', '.join(sorted(set(same))) or '-', ', '.join(nm) or '-'))
out.append('')
for dn in DEV:
    out.append('## %s - non-source files\n' % dn)
    out.append('| file | type | start | len | identical on | ')
    out.append('|--|--|--|--|--|')
    for c in cat[dn]['files']:
        if c['type'] == 'a' and c['start'] == 28019: continue
        oth = sorted(set('%s' % d for d, x in by[c['md5']] if d != dn))
        out.append('| %s | %s | %d | %d | %s |' % (c['name'].strip().replace('|', '/'), c['type'], c['start'], c['length'], ', '.join(oth) or '-'))
    out.append('')
open(ROOT + '/docs/BINARIES.md', 'w', encoding='utf8').write('\n'.join(out))
print('ok')
