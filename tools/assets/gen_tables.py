#!/usr/bin/env python3
"""assets/data/*.csv  ->  build/gen/<LABEL>.inc  (db / dw lines).  Run by build.py before the assembly.
The csv files have '#' comment lines first, then a header row; see tablespec.py for the column -> label mapping."""
import os, sys, csv, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from tablespec import TABLES

HEADER = '; GENERATED by tools/assets/gen_tables.py from assets/data/%s - DO NOT EDIT (edit the csv file)\n'


def rows_of(path):
    lines = [l for l in open(path, encoding='utf-8', newline='').read().split('\n') if l.strip() and not l.startswith('#')]
    return list(csv.DictReader(lines))


def val(s, kind='b', where=''):
    s = (s or '').strip()
    if s == '':
        raise ValueError('%s: empty value' % where)
    if kind == 'k':
        if s == 'SS': return 31
        if s == 'SPACE': return 32
        if len(s) == 1: return ord(s)
    try:
        if s.startswith('#'): v = int(s[1:], 16)
        elif s.lower().startswith('0x'): v = int(s, 16)
        else: v = int(s)
    except ValueError:
        raise ValueError('%s: bad number %r' % (where, s))
    lim = 65535 if kind == 'w' else 255
    if v < -128 or v > lim:
        raise ValueError('%s: value %d out of range for type %s' % (where, v, kind))
    return v & (65535 if kind == 'w' else 255)


def emit_row(vals):
    """vals = [(type, value)] -> db/dw lines (consecutive bytes share one db)"""
    out = []
    cur = []
    for t, v in vals:
        if t == 'w':
            if cur: out.append('db   ' + ','.join(map(str, cur))); cur = []
            out.append('dw   %d' % v)
        else:
            cur.append(v)
    if cur: out.append('db   ' + ','.join(map(str, cur)))
    return out


def write(outdir, label, csvname, lines):
    open(os.path.join(outdir, label + '.inc'), 'w', newline='\n').write(HEADER % csvname + ''.join(('%s\n' % l) if re.match(r'[A-Za-z_]\w*:', l) else ('            %s\n' % l) for l in lines))


def parse_rle(tok, where):
    m = re.fullmatch(r'([0-9A-Fa-f]{2})\*(\d+)', tok)
    if m: return [int(m.group(1), 16)] * int(m.group(2))
    if re.fullmatch(r'[0-9A-Fa-f]{2}', tok): return [int(tok, 16)]
    raise ValueError('%s: bad byte token %r (use two hex digits or XX*N)' % (where, tok))


def generate(root, outdir):
    os.makedirs(outdir, exist_ok=True)
    ddir = os.path.join(root, 'assets', 'data')
    n = 0
    for name, T in TABLES.items():
        rows = rows_of(os.path.join(ddir, T['csv']))
        if T['rows'] is not None and len(rows) != T['rows']:
            raise SystemExit('%s: %d rows expected, %d found' % (T['csv'], T['rows'], len(rows)))
        for lab, cols, tail in T['labels']:
            lines = []
            for ri, r in enumerate(rows):
                vals = [(t, val(r[c], t, '%s row %d column %s' % (T['csv'], ri + 1, c))) for c, t, f in cols]
                lines += emit_row(vals)
            if tail: lines.append('db   ' + ','.join(map(str, tail)))
            write(outdir, lab, T['csv'], lines)
            n += 1
    # settings: environment (labels per row) + game
    rows = rows_of(os.path.join(ddir, 'settings_env.csv'))
    if len(rows) != 13: raise SystemExit('settings_env.csv: 13 rows expected')
    lines = []
    for r in rows:
        lines.append('%s:' % r['label'] + ' ' * max(1, 12 - len(r['label'])) + 'db   %d,%d' % (val(r['value'], 'b', 'settings_env ' + r['label']), val(r['mask'], 'b', 'settings_env ' + r['label'])))
    write(outdir, 'SETSD', 'settings_env.csv', lines)
    write(outdir, 'SETSI', 'settings_env.csv', ['db   %d' % val(r['key'], 'k', 'settings_env key ' + r['label']) for r in rows] + ['db   0'])
    rows = rows_of(os.path.join(ddir, 'settings_game.csv'))
    if len(rows) != 43: raise SystemExit('settings_game.csv: 43 rows expected')
    write(outdir, 'SETGD', 'settings_game.csv', ['db   %d,%d' % (val(r['port'], 'b', 'settings_game id ' + r['id']), val(r['mask'], 'b', 'settings_game id ' + r['id'])) for r in rows])
    write(outdir, 'SETGI', 'settings_game.csv', ['db   %d' % val(r['key'], 'k', 'settings_game key id ' + r['id']) for r in rows] + ['db   0'])
    # new game record
    rows = rows_of(os.path.join(ddir, 'newgame.csv'))
    lines = []
    for r in rows:
        bs = []
        for tok in r['bytes'].split():
            bs += parse_rle(tok, 'newgame.csv ' + r['label'])
        if len(bs) != int(r['size']):
            raise SystemExit('newgame.csv: field %s has %d bytes, size column says %s (the record layout is fixed)' % (r['label'], len(bs), r['size']))
        first = True
        lab = r['label'] + ':'
        if not bs:
            lines.append(lab)
            continue
        for i in range(0, len(bs), 16):
            lines.append((lab if first else '') .ljust(12) + 'db   ' + ','.join(map(str, bs[i:i+16])))
            first = False
    open(os.path.join(outdir, 'NEWGAME.inc'), 'w', newline='\n').write(HEADER % 'newgame.csv' + '\n'.join(lines) + '\n')
    return n + 5


if __name__ == '__main__':
    root = os.path.join(HERE, '..', '..')
    print('gen_tables: %d files' % generate(root, os.path.join(root, 'build', 'gen')))
