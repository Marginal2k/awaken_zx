        ifndef HW_ASM
HW_ASM          equ 1
; --- порты
PORT_PAGE       equ #7FFD               ; управление страницами 128K
PORT_AY_REG     equ #FFFD               ; AY: выбор регистра / чтение (данные - порт #BFFD)
PORT_AY_DATA    equ #BFFD
PORT_ULA        equ #FE                 ; клавиатура / бордюр / звук
PORT_KEMPSTON   equ #1F                 ; джойстик Kempston (и мышь)
; контроллер дисковода WD1793 (прямой доступ, awk5/LOAD)
FDC_COMMAND     equ #1F
FDC_SECTOR      equ #5F
; --- TR-DOS и системные переменные
TRDOS_COMMAND   equ #3D13               ; вход в TR-DOS: C = функция
TRDOS_DRIVE     equ #5D16               ; системная переменная TR-DOS: текущий диск
SYSVAR_IY       equ #5C3A               ; значение IY для ПЗУ (базовый адрес системных переменных)
; --- экран
SCREEN          equ #4000
SCREEN_PIX_LEN  equ #1800
SCREEN_ATTR     equ #5800
SCREEN_ATTR_LEN equ #0300
        endif
