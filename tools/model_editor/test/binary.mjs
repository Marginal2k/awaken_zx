// Test 2: the JS binary encoder equals the bytes the build generated (build/gen/*.inc via gen_models.py and the built OBJECT3D.C)
import fs from 'node:fs';
import path from 'node:path';
import * as F from '../js/format.js';
import { loadAll, ROOT } from './common.mjs';

let bad = 0, models = 0, total = 0;
const eq = (a, b) => a.length === b.length && a.every((v, i) => v === b[i]);
const sets = loadAll();
for (const set of sets) {
  for (const sec of set.ix.sections) {
    const incText = fs.readFileSync(path.join(ROOT, 'build', 'gen', sec.name + '.inc'), 'utf8');
    const inc = F.parseInc(incText);
    const js = [];
    for (const name of sec.models) {
      const e = set.models.find((x) => x.name === name);
      const off = js.length;
      for (const l of e.model.labels) if (inc.labels[l] !== off) { bad++; console.log('label offset', l, inc.labels[l], off); }
      let o = off + 2 + 4 * e.model.groups.length + 1;
      for (const f of e.model.faces) { for (const l of f.labels) if (inc.labels[l] !== o) { bad++; console.log('face label offset', l, inc.labels[l], o); } o += 1 + f.v.length; }
      js.push(...F.toBytes(e.model));
      models++;
      if (F.recordSize(e.model) !== F.toBytes(e.model).length) { bad++; console.log('recordSize', name); }
    }
    if (!eq(js, inc.bytes)) { bad++; console.log('SECTION BYTES DIFFER', sec.name, js.length, inc.bytes.length); }
    total += js.length;
    const lines = ['; GENERATED by tools/assets/gen_models.py from assets/models/' + set.kind + '/*.txt (index.txt: [' + sec.name + ']) - DO NOT EDIT'];
    for (const name of sec.models) lines.push(...F.toInc(set.models.find((x) => x.name === name).model));
    if (lines.join('\n') + '\n' !== incText) { bad++; console.log('INC TEXT DIFFERS', sec.name); }
  }
}
const flight = sets[0];
const all = flight.ix.sections.flatMap((s) => s.models).flatMap((n) => [...F.toBytes(flight.models.find((x) => x.name === n).model)]);
const bank = fs.readFileSync(path.join(ROOT, 'build', 'flight', 'OBJECT3D.C'));
if (!eq(all, [...bank])) { bad++; console.log('OBJECT3D.C differs', all.length, bank.length); }
console.log(`binary: ${models} models, ${total} bytes, OBJECT3D.C ${bank.length} B, ${bad} problems`);
process.exit(bad ? 1 : 0);
