#!/usr/bin/env python3
"""assets/models/{flight,station}/*.txt (+ index.txt)  ->  build/gen/<SECTION>.inc  (OBJECTS, OBJECTS2, OBJECTSS, OBJX).  Format: tools/assets/models.py"""
import os, sys, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import models


def read_index(path):
    secs, cur = [], None
    for l in open(path, encoding='utf-8').read().split('\n'):
        l = l.split('#')[0].strip()
        if not l:
            continue
        m = re.fullmatch(r'\[(\w+)\]', l)
        if m:
            cur = (m.group(1), []); secs.append(cur)
        elif cur is None:
            raise SystemExit('%s: a [SECTION] line is expected first' % path)
        else:
            cur[1].append(l)
    return secs


def generate(root, outdir):
    n = 0
    for kind in ('flight', 'station'):
        d = os.path.join(root, 'assets', 'models', kind)
        for sec, names in read_index(os.path.join(d, 'index.txt')):
            lines = ['; GENERATED by tools/assets/gen_models.py from assets/models/%s/*.txt (index.txt: [%s]) - DO NOT EDIT' % (kind, sec)]
            for nm in names:
                p = os.path.join(d, nm + '.txt')
                if not os.path.exists(p):
                    raise SystemExit('%s: model file %s.txt not found' % (os.path.join(d, 'index.txt'), nm))
                lines += models.to_inc(models.from_text(open(p, encoding='utf-8').read(), '%s/%s.txt' % (kind, nm)))
            open(os.path.join(outdir, sec + '.inc'), 'w', newline='\n').write('\n'.join(lines) + '\n')
            n += 1
    return n


if __name__ == '__main__':
    root = os.path.join(HERE, '..', '..')
    os.makedirs(os.path.join(root, 'build', 'gen'), exist_ok=True)
    print('gen_models: %d files' % generate(root, os.path.join(root, 'build', 'gen')))
