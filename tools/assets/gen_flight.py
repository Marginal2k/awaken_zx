#!/usr/bin/env python3
"""Flight data: assets/data/{spawn_*,ship_choice,newgame_flight}.csv, assets/gfx/radar_sprites.{png,csv}, assets/sound/effects.txt
   ->  build/gen/{VERTAB,STROYTAB,LEVLTAB,INDTAB,NDATA,RADAR_COMPASS,RADAR_BLIPS,RADAR_TARGET,EFFECTS}.inc   (included by the flight sources)."""
import os, sys, csv, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from PIL import Image

HDR = '; GENERATED by tools/assets/gen_flight.py from %s - DO NOT EDIT (edit the source file)\n'


def num(s, where, lo=-128, hi=255):
    s = (s or '').strip()
    try:
        if s.startswith('%'): v = int(s[1:], 2)
        elif s.startswith('#'): v = int(s[1:], 16)
        elif s.lower().startswith('0x'): v = int(s, 16)
        else: v = int(s, 10)
    except ValueError:
        raise SystemExit('%s: bad number %r' % (where, s))
    if not lo <= v <= hi:
        raise SystemExit('%s: %d out of range %d..%d' % (where, v, lo, hi))
    return v


def rows_of(path):
    lines = [l for l in open(path, encoding='utf-8', newline='').read().split('\n') if l.strip() and not l.startswith('#')]
    return list(csv.DictReader(lines))


def write(outdir, name, src, lines):
    open(os.path.join(outdir, name + '.inc'), 'w', newline='\n').write(HDR % src + '\n'.join(lines) + '\n')


def parse_rle(tok, where):
    m = re.fullmatch(r'([0-9A-Fa-f]{2})\*(\d+)', tok)
    if m: return [int(m.group(1), 16)] * int(m.group(2))
    if re.fullmatch(r'[0-9A-Fa-f]{2}', tok): return [int(tok, 16)]
    raise SystemExit('%s: bad byte token %r' % (where, tok))


def db(vals):
    return '            db   ' + ','.join(str(v & 255) for v in vals)


def spawn(root, ddir, out):
    rows = rows_of(os.path.join(ddir, 'spawn_types.csv'))
    if len(rows) != 5: raise SystemExit('spawn_types.csv: 5 rows expected (democracy, dictatorship, anarchy, uninhabited, unknown)')
    L = ['VERTAB:']
    for i, r in enumerate(rows):
        v = [num(r[c], 'spawn_types.csv row %d %s' % (i + 1, c), 0, 255) for c in list(r)[1:10]]
        if v != sorted(v): raise SystemExit('spawn_types.csv row %d: the cumulative thresholds must not decrease' % (i + 1))
        L.append(db(v))
        if i < 4: L.append('            ds   7')
    write(out, 'VERTAB', 'assets/data/spawn_types.csv', L)
    rows = rows_of(os.path.join(ddir, 'spawn_government.csv'))
    if len(rows) != 4: raise SystemExit('spawn_government.csv: 4 rows expected')
    L = ['STROYTAB:']
    for i, r in enumerate(rows):
        v = [num(r['p%02d' % k], 'spawn_government.csv row %d p%02d' % (i + 1, k)) for k in range(1, 16)]
        if i < 3: v.append(num(r['void'] or '0', 'spawn_government.csv void'))
        L.append(db(v))
    write(out, 'STROYTAB', 'assets/data/spawn_government.csv', L)
    rows = rows_of(os.path.join(ddir, 'spawn_level.csv'))
    if len(rows) != 15: raise SystemExit('spawn_level.csv: 15 rows expected')
    L = ['LEVLTAB:']
    for i, r in enumerate(rows):
        L.append(db([num(r['base'], 'spawn_level.csv base', 0, 255), num(r['mult'], 'spawn_level.csv mult'), num(r['div'], 'spawn_level.csv div', 0, 255)]))
    write(out, 'LEVLTAB', 'assets/data/spawn_level.csv', L)


def ship_choice(ddir, out):
    rows = rows_of(os.path.join(ddir, 'ship_choice.csv'))
    L, cur, cnt = [], None, {}
    for r in rows:
        t = r['table']
        if t != cur:
            L.append('%s:' % t); cur = t
        cnt[t] = cnt.get(t, 0) + 1
        w = num(r['weight'], 'ship_choice.csv weight', 0, 255)
        L.append('            db   %s,%d' % (r['model'].strip(), w))
    for t, n in cnt.items():
        if n != 8: raise SystemExit('ship_choice.csv: table %s has %d slots, 8 expected' % (t, n))
    write(out, 'INDTAB', 'assets/data/ship_choice.csv', L)


def newgame_flight(ddir, out):
    L = ['NDATA:']
    total = 0
    for r in rows_of(os.path.join(ddir, 'newgame_flight.csv')):
        bs = []
        for tok in r['bytes'].split():
            bs += parse_rle(tok, 'newgame_flight.csv ' + r['label'])
        if len(bs) != int(r['size']):
            raise SystemExit('newgame_flight.csv: field %s has %d bytes, size column says %s' % (r['label'], len(bs), r['size']))
        total += len(bs)
        for i in range(0, len(bs), 16):
            L.append(db(bs[i:i + 16]))
    write(out, 'NDATA', 'assets/data/newgame_flight.csv', L)


def sprites(gfx, out):
    im = Image.open(os.path.join(gfx, 'radar_sprites.png')).convert('L')
    px = im.load()
    info = {}
    for r in rows_of(os.path.join(gfx, 'radar_sprites.csv')):
        n, size = int(r['cell']), int(r['size'])
        ox, oy = (n % 8) * 8, (n // 8) * 8
        base = []
        for y in range(size):
            v = 0
            for x in range(8):
                if px[ox + x, oy + y] < 128: v |= 0x80 >> x
            base.append(v)
        for y in range(size, 8):
            for x in range(8):
                if px[ox + x, oy + y] < 128:
                    raise SystemExit('radar_sprites.png: sprite %s has pixels below its height %d' % (r['name'], size))
        info[r['name']] = (size, base)
        if size == 3 and any(b & 0x1F for b in base):
            raise SystemExit('radar_sprites.png: blip %s is wider than 3 pixels' % r['name'])

    def emit(name, label=True):
        size, base = info[name]
        L = ['%s:' % name] if label else []
        for p in range(8):
            for b in base:
                v = b << 8 >> p
                L.append('            db   %%%s,%%%s' % (format(v >> 8 & 255, '08b'), format(v & 255, '08b')))
        return L
    write(out, 'RADAR_COMPASS', 'assets/gfx/radar_sprites.png', sum((emit(n) for n in ('VISUN', 'UVISUN', 'VIEAR', 'UVIEAR')), []))
    write(out, 'RADAR_BLIPS', 'assets/gfx/radar_sprites.png', sum((emit(n) for n in ('MCARGO', 'MROKET', 'MSTATION', 'MTRADER', 'MARMY', 'MMIKR', 'MOTSHEL', 'MHUNTER', 'MUFO', 'MUNKNOWN', 'MPIRAT', 'MPOLICE')), []))
    write(out, 'RADAR_TARGET', 'assets/gfx/radar_sprites.png', emit('MASPR') + emit('MLOCK', False))


def effects(root, out):
    L, cur, n = [], None, 0
    path = os.path.join(root, 'assets', 'sound', 'effects.txt')
    for ln, l in enumerate(open(path, encoding='utf-8').read().split('\n'), 1):
        l = re.sub(r'\s*;.*$', '', l.strip())
        if not l or l.startswith('#'):
            continue
        m = re.fullmatch(r'\[(\w+)\]', l)
        if m:
            if cur is not None: L.append(db([0]))
            L.append('%s:' % m.group(1)); cur = m.group(1); n = 0
            continue
        if cur is None:
            raise SystemExit('effects.txt line %d: [LABEL] expected first' % ln)
        w = l.split()
        if len(w) != 4:
            raise SystemExit('effects.txt line %d: 4 numbers expected (tone_lo tone_hi mixer volume)' % ln)
        v = [num(a, 'effects.txt line %d' % ln, 0, 255) for a in w]
        if v[0] == 0:
            raise SystemExit('effects.txt line %d: tone_lo 0 would end the effect (use 1 instead)' % ln)
        if v[3] > 15:
            raise SystemExit('effects.txt line %d: volume must be 0..15' % ln)
        L.append('            db   %d,%d,%s,%d' % (v[0], v[1], '%' + format(v[2], '08b'), v[3]))
    L.append(db([0]))
    write(out, 'EFFECTS', 'assets/sound/effects.txt', L)


def generate(root, outdir):
    ddir = os.path.join(root, 'assets', 'data')
    os.makedirs(outdir, exist_ok=True)
    spawn(root, ddir, outdir)
    ship_choice(ddir, outdir)
    newgame_flight(ddir, outdir)
    sprites(os.path.join(root, 'assets', 'gfx'), outdir)
    effects(root, outdir)
    return 9


if __name__ == '__main__':
    root = os.path.join(HERE, '..', '..')
    print('gen_flight: %d files' % generate(root, os.path.join(root, 'build', 'gen')))
