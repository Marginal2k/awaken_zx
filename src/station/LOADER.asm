;==============================================================================
; LOADER - загрузчик оверлеев станции (исполняется по адресу #4000)
;
; Где живёт: включается из BODYOCUR внутри блока disp #4000; работает из экранной RAM, поэтому
; после работы код затирается картинкой.
;
; Что делает: по TR-DOS (макросы src/common/disk.asm) грузит KARTA -> страница PGKRT (#C000),
; MUZ1 -> PGMUZ (#DB00, запуск call #DB00), HELP -> PGHLP (#DB00), D3D -> PG3D (#C000), LANG -> PGLANG,
; затем обнуляет матрицы поворота 3D и возвращается. Таблица DISK_SECTAB (секторы 16 картинок stscr)
; подставляется из gen/SECTAB.inc.
;==============================================================================

            jr   .LoadFiles
.FileKarta   ; orig: FILE1
            db   "KARTA   C"
.FileMuz   ; orig: FILE2
            db   "MUZ1    C"
.FileStscr   ; orig: FILE3
            db   "stscr   C"
.FileHelp   ; orig: FILE4
            db   "HELP    C"
.File3D   ; orig: FILE5
            db   "D3D     C"
.FileLang   ; orig: FILE6
            db   "LANG    C"
; SECTAB: sector counts of the 16 packed stscr pictures (the file holds all 16 one after another;
; the catalogue length 3230 is only the first picture, the sector count is 239).  Present in the
; v0.2 demo binary; the source line was disabled in the last saved ZASM source.
.DISK_SECTAB
            include "gen/SECTAB.inc"      ; GENERATED by tools/assets/gen_gfx.py
.LoadFiles   ; orig: LD1
;  Загр. страницы
            ld   a,9
            ld   (TRDOS_DRIVE),a
            PAGE_ PGKRT
                        DISK_SETNAME .FileKarta
            ld   hl,#C000
            DISK_READ
            PAGE_ PGMUZ
                        DISK_SETNAME .FileMuz
            ld   hl,#DB00
            DISK_READ
            call #DB00
            PAGE_ PGHLP
                        DISK_SETNAME .FileHelp
            ld   hl,#DB00
            DISK_READ
            PAGE_ PG3D
                        DISK_SETNAME .File3D
            ld   hl,#C000
            DISK_READ

;  Общая инициализация
            xor  a
            ld   l,a
            ld   h,a
            ld   (Eye_a),hl
            ld   (Eye_g),a
            ld   (La12+1),hl
            ld   (La21+1),hl
            ld   (La31+1),hl
            ld   (La32+1),hl
            ld   (Lb13+1),hl
            ld   (Lb23+1),hl
            ld   hl,#7FFF
            ld   (La11+1),hl
            ld   (La22+1),hl
            ld   (Lb33+1),hl


            PAGE_ PGLANG
                        DISK_SETNAME .FileLang
            ld   hl,#C000
            DISK_READ

            PAGE_ PGBGD
                        DISK_SETNAME .FileStscr
            DISK_FIND
            ld   a,c
            DISK_INFO
            ld   a,r
            and  #0F
            ld   c,a
            ld   l,a
            ld   h,0
            ld   de,.DISK_SECTAB
            add  hl,de
            push hl
            inc  c
            EXD
            xor  a
._M2_
            dec  c
            jr   z,._M_
            add  a,(hl)
            inc  hl
            jr   ._M2_
._M_
            ld   de,(TRDOS_SECTOR)
            ld   c,a
            and  #0F
            add  a,e
            ld   e,a
            rrca
            rrca
            rrca
            rrca
            and  #0F
            add  a,d
            ld   d,a
            ld   a,c
            rrca
            rrca
            rrca
            rrca
            and  #0F
            add  a,d
            ld   d,a
            ld   a,e
            and  #0F
            ld   e,a
            pop  hl
            ld   b,(hl)
            ld   hl,#C000
            DISK_RDSEC
            ld   hl,#C000
            ld   de,#C000
            call DEPACK

; Делаем цвет для часов
            ld   hl,#3838
            ld   (#DAFE),hl
            ld   (#DAFC),hl
            ld   (#DAFB),hl

            PAGE_ PGNORM
